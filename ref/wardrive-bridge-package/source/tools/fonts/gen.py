"""Rasterize the screen fonts into 4-bit anti-aliased glyph tables for lcd.c.
Usage: gen.py <font dir> <out .h>  (fonts from github.com/google/fonts: ofl/orbitron, ofl/rajdhani, ofl/sharetechmono)"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

src, out = sys.argv[1], sys.argv[2]
ASCII = "".join(chr(c) for c in range(32, 127))
# name, file, weight (variable fonts), px, charset, comment
FONTS = [
    ("font_huge",  "Orbitron[wght].ttf", 800, 56, "0123456789+", "AP count"),
    ("font_big",   "Orbitron[wght].ttf", 800, 40, "0123456789+", "AP count, 6+ digits"),
    ("font_num",   "Orbitron[wght].ttf", 800, 28, "0123456789+", "AP count on the 128x128 screen, 5+ digits"),
    ("font_logo",  "Orbitron[wght].ttf", 900, 30, "ADEIRVW", "splash wordmark"),
    ("font_head",  "Orbitron[wght].ttf", 900, 20, ASCII, "header, alert label"),
    ("font_title", "Orbitron[wght].ttf", 700, 15, ASCII, "section titles, banners"),
    ("font_med",   "Rajdhani-Bold.ttf", None, 24, ASCII, "values"),
    ("font_mid",   "Rajdhani-Bold.ttf", None, 20, ASCII, "link status"),
    ("font_small", "ShareTechMono-Regular.ttf", None, 13, ASCII, "labels"),
]

lines = ["// Generated by gen.py from SIL OFL 1.1 fonts (see NOTICE.md): 4-bit anti-aliased glyphs, packed two per byte,",
         "// row-major, high nibble first. Glyph y offsets are from the top of the line (ascent above the baseline).",
         "// SPDX-License-Identifier: OFL-1.1", "#pragma once", "#include <stdint.h>", "",
         "typedef struct { uint8_t w, h; int8_t xo, yo; uint8_t adv; uint32_t off; } lcd_glyph_t;",
         "typedef struct { uint8_t first, last, ascent, height; const lcd_glyph_t *g; const uint8_t *bits; } lcd_font_t;", ""]
total = 0
for name, file, wght, px, chars, why in FONTS:
    f = ImageFont.truetype(os.path.join(src, file), px)
    if wght: f.set_variation_by_axes([wght])
    asc, desc = f.getmetrics()
    first, last = ord(min(chars)), ord(max(chars))
    glyphs, bits = [], bytearray()
    for c in range(first, last + 1):
        ch = chr(c)
        if ch not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0)); continue
        adv = round(f.getlength(ch))
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if w == 0 or h == 0:
            glyphs.append((0, 0, 0, 0, adv, len(bits))); continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
        px_ = img.tobytes()
        off = len(bits)
        nib = [min(15, (v + 8) // 17) for v in px_]
        if len(nib) & 1: nib.append(0)
        for i in range(0, len(nib), 2): bits.append((nib[i] << 4) | nib[i + 1])
        glyphs.append((w, h, x0, y0 + asc, adv, off))
    total += len(bits) + len(glyphs) * 8
    lines.append(f"// {name}: {file} {wght or ''} {px} px, {why}")
    lines.append(f"static const uint8_t {name}_bits[] = {{")
    for i in range(0, len(bits), 24):
        lines.append("    " + ",".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const lcd_glyph_t {name}_g[] = {{")
    for g in glyphs: lines.append("    {%d,%d,%d,%d,%d,%d}," % g)
    lines.append("};")
    lines.append(f"static const lcd_font_t {name} = {{ {first}, {last}, {asc}, {asc + desc}, {name}_g, {name}_bits }};")
    lines.append("")
open(out, "w", newline="\n").write("\n".join(lines))
print("bytes", total)
