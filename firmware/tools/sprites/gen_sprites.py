"""Convert the screen sprites to RGB565 + 4-bit alpha tables for lcd_draw.c.
Usage: gen_sprites.py <out .h>   (sources next to this script)"""
import os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
# name, source, height in px (width follows the aspect ratio)
SPRITES = [
    ("spr_toy", "adult_toy_rain.png", 96, "adult-toy alert, 240x320 screen (the app's toy-shower sprite)"),
    ("spr_toy_s", "adult_toy_rain.png", 46, "adult-toy alert, 128x128 screen"),
]

out = ["// Generated by tools/sprites/gen_sprites.py: RGB565 pixels plus 4-bit alpha (two per byte, high nibble first).",
       "// SPDX-License-Identifier: MIT", "#pragma once", "#include <stdint.h>", "",
       "typedef struct { uint8_t w, h; const uint16_t *px; const uint8_t *alpha; } lcd_sprite_t;", ""]
total = 0
for name, src, h, why in SPRITES:
    im = Image.open(os.path.join(HERE, src)).convert("RGBA")
    w = max(1, round(im.width * h / im.height))
    im = im.resize((w, h), Image.LANCZOS)
    px, al = [], []
    raw = im.tobytes()
    for i in range(0, len(raw), 4):
        r, g, b, a = raw[i:i + 4]
        px.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
        al.append(min(15, (a + 8) // 17))
    if len(al) & 1: al.append(0)
    ab = [(al[i] << 4) | al[i + 1] for i in range(0, len(al), 2)]
    total += len(px) * 2 + len(ab)
    out.append(f"// {name}: {src}, {w}x{h}, {why}")
    out.append(f"static const uint16_t {name}_px[] = {{")
    for i in range(0, len(px), 16): out.append("    " + ",".join(f"0x{v:04x}" for v in px[i:i + 16]) + ",")
    out.append("};")
    out.append(f"static const uint8_t {name}_a[] = {{")
    for i in range(0, len(ab), 24): out.append("    " + ",".join(f"0x{v:02x}" for v in ab[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const lcd_sprite_t {name} = {{ {w}, {h}, {name}_px, {name}_a }};")
    out.append("")
open(sys.argv[1], "w", newline="\n").write("\n".join(out))
print("bytes", total)
